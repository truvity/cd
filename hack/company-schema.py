#!/usr/bin/env python3
"""Compose the adapter schemas from the schemas of the charts they adapt.

cd-company's from cd-delivery's platform/product schema; cd-project's from the
same, per cluster, plus the allowlisted part of cd-pipeline's and the defaults
of its two packaged dependencies (held constant, so nothing reaches them).
Run after changing cd-delivery, cd-company or cd-pipeline; --check refuses
drift without writing anything. The packaged chart dependencies are maintained
with `just vendor cd-company` and `just vendor cd-project`.
"""

import argparse
import copy
import json
import subprocess
from pathlib import Path

NAME = {"type": "string", "pattern": "^[a-z0-9]([-a-z0-9]*[a-z0-9])?$", "maxLength": 63}
RINGS = {
    "type": "object",
    "additionalProperties": False,
    "properties": {ring: {"type": "object"} for ring in ("infra", "app", "e2e")},
}


def delivery_schema(root):
    return json.loads((root / "charts/cd-delivery/values.schema.json").read_text())


def company_product(source):
    """cd-delivery's product, less the pin and values the company supplies."""
    product = copy.deepcopy(source["properties"]["products"]["additionalProperties"])
    for key in ("pin", "values"):
        del product["properties"][key]
    product["required"].remove("pin")
    return product


def project_product(source):
    """cd-company's product, less the chart source and kind: the company's project.source."""
    product = company_product(source)
    for key in ("repository", "chart", "kind"):
        del product["properties"][key]
    # What a kind requires is decided by project.source.kind (KIND_RULES).
    del product["allOf"]
    return product


# The platform's product facts by the company's kind: a single chart takes
# a namespace and nothing else (cd-delivery refuses the rest by name); a
# product needs its interface and hostname.
KIND_RULES = [{
    "if": {
        "required": ["project"],
        "properties": {"project": {"required": ["source"], "properties": {"source": {"required": ["kind"], "properties": {"kind": {"const": "chart"}}}}}},
    },
    "then": {"properties": {"products": {"additionalProperties": {"propertyNames": {"enum": ["namespace"]}}}}},
    "else": {"properties": {"products": {"additionalProperties": {"required": ["interface", "hostname"]}}}},
}]


def generated_schema(root):
    source = delivery_schema(root)
    product = company_product(source)
    name = NAME
    rings = RINGS
    schema = {
        "$schema": source["$schema"],
        "$comment": "Generated by hack/company-schema.py; platform/product facts come from cd-delivery.",
        "title": "cd-company",
        "type": "object",
        "additionalProperties": False,
        "properties": {
            "platform": source["properties"]["platform"],
            "products": {"type": "object", "propertyNames": name, "additionalProperties": product},
            "services": {"type": "array", "uniqueItems": True, "items": name},
            "pins": {"type": "object", "propertyNames": name, "additionalProperties": {"type": "string"}},
            "values": {"type": "object", "propertyNames": name, "additionalProperties": rings},
            "global": source["properties"]["global"],
            # Keep the application's own product map empty: only the parent's
            # explicit named-template call may render Applications.
            "cd-delivery": {
                "type": "object", "additionalProperties": False,
                "properties": {
                    "platform": {"$ref": "#/properties/platform"},
                    "products": {
                        "type": "object", "additionalProperties": False,
                        "maxProperties": 0,
                        "description": "Reserved: cd-delivery.products must remain empty; use the parent adapter inputs.",
                    },
                    "global": {"$ref": "#/properties/global"},
                },
            },
        },
    }
    return json.dumps(schema, indent=2) + "\n"


def chart_defaults(root, chart):
    """A chart's values.yaml as JSON (yq, which devbox provides)."""
    out = subprocess.run(
        ["yq", "-o=json", ".", str(root / "charts" / chart / "values.yaml")],
        check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def frozen(defaults, nested=None):
    """A dependency's values, held to its own defaults: every key constant
    except Helm's `global`, so neither file may reach the subchart."""
    properties = {key: {"const": value} for key, value in defaults.items()}
    properties["global"] = {"$ref": "#/properties/global"}
    properties.update(nested or {})
    return {"type": "object", "additionalProperties": False, "properties": properties}


def generated_project_schema(root):
    source = delivery_schema(root)
    pipeline = json.loads((root / "charts/cd-pipeline/values.schema.json").read_text())
    pp = pipeline["properties"]
    chart = pp["projects"]["items"]["properties"]["chart"]["properties"]
    git = copy.deepcopy(pp["git"])
    git["properties"] = {"repoURL": git["properties"]["repoURL"]}
    git["description"] = "The repository a promotion writes the pin to. The write-back credentials are the platform's and are not rendered here."
    graph = copy.deepcopy(pp["graph"])
    graph["properties"] = {key: graph["properties"][key] for key in ("upstreams", "applicationName", "promotedVersion")}
    graph["description"] = (
        "The promotion graph: with promotedVersion every derived Stage names the promoted-version check, whose "
        "objects are the platform's and never rendered here; no access subjects here."
    )
    names = {"type": "array", "uniqueItems": True, "items": NAME}
    schema = {
        "$schema": source["$schema"],
        "$comment": "Generated by hack/company-schema.py; platform/product facts come from cd-delivery, pipeline settings from cd-pipeline.",
        "title": "cd-project",
        "type": "object",
        "additionalProperties": False,
        "required": ["project", "clusters", "platformDigest"],
        "allOf": KIND_RULES,
        "properties": {
            "project": {
                "type": "object", "additionalProperties": False,
                "description": "Company-owned: the project, its charts, clusters and promotion order.",
                "required": ["name", "source", "clusters", "pipeline"],
                "properties": {
                    "name": dict(NAME, description="The project: the service name of its Applications, its Kargo Project, namespace and Warehouse."),
                    "source": {
                        "type": "object", "additionalProperties": False,
                        "required": ["chart", "semver"],
                        "properties": {
                            "chart": dict(chart["repoURL"], description="The application chart, oci://<repository>/<chart>: what the Warehouse subscribes to, and the repository and chart of every ring's Application (<chart>, <chart>-infra, <chart>-e2e)."),
                            "infraChart": dict(chart["repoURL"], description="The infra chart, released with the application chart and installed at its pin; must be <chart>-infra. Refused for a kind with no infra ring."),
                            "semver": chart["semver"],
                            "versionPrefix": chart["versionPrefix"],
                            "subscribeAs": chart["subscribeAs"],
                            "kind": {"type": "string", "enum": ["product", "chart"], "description": "The kind of product, put into every cluster's product facts: product (default; <chart>, <chart>-infra, <chart>-e2e) or chart (the app ring alone, no infraChart). A static site has no chart for the Warehouse and is not accepted."},
                        },
                    },
                    "sources": {
                        "type": "object",
                        "propertyNames": dict(NAME, maxLength=30, **{"not": {"const": "default"}}),
                        "description": "Further sources of the same product, by name: each one a Warehouse of its own, <project>-<name>, and the repository the clusters that take it (pipeline.stageSources) install every ring from. `kind` and the ring charts are project.source's; the chart name must be the same.",
                        "additionalProperties": {
                            "type": "object", "additionalProperties": False,
                            "required": ["chart", "semver"],
                            "properties": {
                                "chart": dict(chart["repoURL"], description="oci://<repository>/<chart>, with project.source.chart's <chart>: <chart>-infra and <chart>-e2e come from the same repository."),
                                "semver": chart["semver"],
                                "versionPrefix": chart["versionPrefix"],
                                "subscribeAs": chart["subscribeAs"],
                            },
                        },
                    },
                    "clusters": dict(names, minItems=1, description="The clusters the project runs on; each one the platform registered (clusters)."),
                    "pipeline": {
                        "type": "object", "additionalProperties": False,
                        "required": ["stageOrder"],
                        "properties": {
                            "stageOrder": dict(names, minItems=1, description="The Stages, in order; each one a cluster of project.clusters whose pin it writes."),
                            "autoPromote": dict(names, description="Stages that promote on their own although they have an upstream."),
                            "upstreams": {"type": "object", "propertyNames": NAME, "additionalProperties": {"type": "array", "items": NAME}, "description": "Replaces pipeline.graph.upstreams for the Stages it names."},
                            "stageSources": {"type": "object", "propertyNames": NAME, "additionalProperties": NAME, "description": "Stage -> a key of project.sources: the Warehouse the Stage takes Freight from and the repository its cluster installs from. A Stage it does not name takes project.source. A Stage and its upstream take the same source; an empty upstreams entry takes Freight straight from the Warehouse."},
                        },
                    },
                },
            },
            "values": {
                "type": "object", "propertyNames": NAME, "additionalProperties": RINGS,
                "description": "Company-owned ring payloads per cluster of project.clusters, held to cd-company's ownership rules.",
            },
            "pins": {
                "type": "object", "propertyNames": NAME, "additionalProperties": {"type": "string"},
                "description": "Company-owned (Kargo writes them): the version per cluster of project.clusters; an empty string is dormant.",
            },
            "clusters": dict(names, minItems=1, description="Platform-owned: the clusters the platform registered for this project."),
            "platform": {
                "type": "object", "propertyNames": NAME, "additionalProperties": source["properties"]["platform"],
                "description": "Platform-owned: cd-company's platform block, per cluster.",
            },
            "products": {
                "type": "object", "propertyNames": NAME, "additionalProperties": project_product(source),
                "description": "Platform-owned: the project's product facts, per cluster (cd-company's products.<service>).",
            },
            "pipeline": {
                "type": "object", "additionalProperties": False,
                "description": "Platform-owned: the allowlisted cd-pipeline settings. No credentials, verification, access, Project or AppProjects.",
                "properties": {
                    "labels": pp["labels"],
                    "annotations": pp["annotations"],
                    "waves": pp["waves"],
                    "argocd": pp["argocd"],
                    "git": git,
                    "promotion": pp["promotion"],
                    "jobs": pp["jobs"],
                    "graph": graph,
                },
            },
            "platformDigest": {
                "type": "string", "pattern": "^[0-9a-f]{64}$",
                "description": "Platform-owned: sha256 of toJson of {clusters, pipeline, platform, products} as the platform passes them.",
            },
            "global": source["properties"]["global"],
            "cd-company": frozen(
                chart_defaults(root, "cd-company"),
                {"cd-delivery": frozen(chart_defaults(root, "cd-delivery"))},
            ),
            "cd-pipeline": frozen(chart_defaults(root, "cd-pipeline")),
        },
    }
    return json.dumps(schema, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    for chart, generate in (("cd-company", generated_schema), ("cd-project", generated_project_schema)):
        path = root / "charts" / chart / "values.schema.json"
        content = generate(root)
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.exit(1, f"{chart} schema drifted; run python3 hack/company-schema.py\n")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
